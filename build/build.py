"""
Generates the .exe executable with PyInstaller.

Usage:
    python build/build.py
    python build/build.py --version 2.0.0

Agents are bundled inside the exe (no external .py files or signatures needed).
To distribute an update: build a new exe and run installer/update.ps1 on the client.
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT     = Path(__file__).parent.parent
DIST_DIR = ROOT / "dist"
EXE_DIR  = DIST_DIR / "exe"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", help="Version to build (default: from config.json)")
    args = parser.parse_args()

    version = (args.version or "2.0.0").lstrip("v")

    # Embed version in dispatcher/version.py so the exe knows its own version
    version_file = ROOT / "dispatcher" / "version.py"
    version_file.write_text(
        f"# Auto-generated by build/build.py — do not edit manually.\n"
        f'APP_VERSION = "{version}"\n',
        encoding="utf-8",
    )
    print(f"  version.py -> APP_VERSION = '{version}'")

    print(f"Building ATANA Agents v{version}...")

    # Verificar binarios de ffmpeg antes de buildear
    ffmpeg_dir  = ROOT / "tools" / "ffmpeg"
    ffmpeg_exe  = ffmpeg_dir / "ffmpeg.exe"
    ffprobe_exe = ffmpeg_dir / "ffprobe.exe"
    if not ffmpeg_exe.exists():
        print(
            f"\nERROR: ffmpeg.exe no encontrado en {ffmpeg_dir}\n"
            f"  Descargar desde https://ffmpeg.org/download.html\n"
            f"  (build estático Windows 64-bit — enlace directo: https://www.gyan.dev/ffmpeg/builds/)\n"
            f"  Copiar ffmpeg.exe y ffprobe.exe a tools/ffmpeg/\n"
        )
        sys.exit(1)
    if not ffprobe_exe.exists():
        print(f"\nERROR: ffprobe.exe no encontrado en {ffmpeg_dir}\n")
        sys.exit(1)
    print(f"  ffmpeg.exe: {ffmpeg_exe} ({ffmpeg_exe.stat().st_size:,} bytes)")
    print(f"  ffprobe.exe: {ffprobe_exe} ({ffprobe_exe.stat().st_size:,} bytes)")

    # Clean only the exe output — preserve dist/release/ (signed agents)
    if EXE_DIR.exists():
        shutil.rmtree(EXE_DIR)
    EXE_DIR.mkdir(parents=True, exist_ok=True)

    # Playwright driver — bundled so the exe can install Chromium on client machines
    # without needing Python installed. Chromium itself is NOT bundled (too large);
    # it downloads automatically on first use via _ensure_chromium() in capture.py.
    import playwright as _pw
    playwright_driver = str(Path(_pw.__file__).parent / "driver")
    playwright_driver_dest = "playwright/driver"

    manifest = str(ROOT / "build" / "atana_dispatcher.manifest")
    icon     = str(ROOT / "installer" / "atana.ico")

    # Run PyInstaller
    result = subprocess.run([
        sys.executable, "-m", "PyInstaller",
        "--clean",
        "--onefile",
        "--noconsole",   # No console window — tray/service run silently; logs go to files via NSSM
        "--name", "atana_dispatcher",
        "--distpath", str(EXE_DIR),
        "--workpath", str(ROOT / "build" / "work"),
        "--specpath", str(ROOT / "build"),

        # Ícono del exe y del instalador Inno Setup
        "--icon", icon,

        # UAC manifest — requests admin elevation on launch
        "--manifest", manifest,

        # Playwright driver — lets the exe install Chromium on client machines
        # without Python. Chromium itself downloads on first use (~15s).
        "--add-data", f"{playwright_driver}{os.pathsep}{playwright_driver_dest}",

        # UI modes — loaded dynamically via --tui / --tray / --setup-db flags
        "--hidden-import", "ui.tui",
        "--hidden-import", "ui.tray",
        "--hidden-import", "ui.setup_db",

        # Session capture — loaded dynamically via --capture-session flag
        "--hidden-import", "dispatcher.capture",
        "--hidden-import", "dispatcher.autoupdater",
        "--hidden-import", "dispatcher.version",

        # Agents — bundled inside the exe (no external .py files needed)
        "--hidden-import", "agents.base",
        "--hidden-import", "agents.prisma",
        "--hidden-import", "agents.cabal",
        "--hidden-import", "agents.naranjax",
        "--hidden-import", "agents.fiserv",
        "--hidden-import", "agents.amex",
        "--hidden-import", "agents.getnet",
        "--hidden-import", "agents.mercadopago",
        "--hidden-import", "shared.imap_reader",
        "--hidden-import", "shared.file_manager",
        "--hidden-import", "shared.session_store",
        "--hidden-import", "shared.paths",

        # Scheduler / DB / HTTP
        "--hidden-import", "pyodbc",
        "--hidden-import", "apscheduler",
        "--hidden-import", "apscheduler.schedulers.background",
        "--hidden-import", "apscheduler.triggers.cron",
        "--hidden-import", "httpx",
        "--hidden-import", "loguru",

        # Cryptography (Fernet for credential encryption in db.py)
        "--hidden-import", "cryptography",
        "--hidden-import", "cryptography.fernet",
        "--hidden-import", "cryptography.hazmat.primitives.kdf.pbkdf2",

        # Browser automation
        "--hidden-import", "playwright",
        "--hidden-import", "playwright_stealth",
        "--collect-data", "playwright_stealth",

        # System tray + icon generation
        "--hidden-import", "pystray",
        "--hidden-import", "pystray._win32",
        "--hidden-import", "PIL",
        "--hidden-import", "PIL.Image",
        "--hidden-import", "PIL.ImageDraw",
        "--collect-submodules", "PIL",

        # pyzbar necesita libzbar-64.dll (incluida en el paquete); --collect-all la copia
        "--collect-all", "pyzbar",

        # curl_cffi tiene libcurl y binarios SSL nativos; --collect-all los empaqueta
        "--collect-all", "curl_cffi",

        # textual carga CSS desde su paquete en runtime; --collect-data lo incluye
        "--collect-data", "textual",

        # OTP (Fiserv TOTP authentication)
        "--hidden-import", "pyotp",
        "--hidden-import", "pyzbar",
        "--hidden-import", "pyzbar.pyzbar",

        # Audio transcription — reCAPTCHA resolver gratuito (Fiserv)
        "--hidden-import", "speech_recognition",
        "--hidden-import", "pydub",
        "--hidden-import", "pydub.utils",
        "--hidden-import", "pydub.audio_segment",
        "--hidden-import", "whisper",

        # ffmpeg empaquetado — pydub/whisper lo usan para conversión de audio
        # Los binarios van en tools/ffmpeg/ y se extraen a sys._MEIPASS/ffmpeg/
        "--add-binary", f"{ffmpeg_exe}{os.pathsep}ffmpeg",
        "--add-binary", f"{ffprobe_exe}{os.pathsep}ffmpeg",

        # tkinter is bundled with Python — no hidden import needed

        # NOTE: config.json is NOT embedded — each client has their own
        str(ROOT / "dispatcher" / "main.py"),
    ], cwd=ROOT)

    if result.returncode != 0:
        print("ERROR: Build failed")
        sys.exit(1)

    # Locate the generated exe
    exe = EXE_DIR / "atana_dispatcher.exe"
    if not exe.exists():
        exe = EXE_DIR / "atana_dispatcher"   # Linux/Mac

    sha256 = _sha256(exe)
    size   = exe.stat().st_size

    # Save build info alongside the exe
    build_info = {
        "version":    version,
        "sha256":     sha256,
        "size":       size,
        "built_at":   datetime.now().isoformat(),
        "executable": exe.name,
    }
    (EXE_DIR / "build_info.json").write_text(json.dumps(build_info, indent=2))

    print(f"\nBuild successful:")
    print(f"  File:    {exe}")
    print(f"  Size:    {size:,} bytes")
    print(f"  SHA256:  {sha256}")
    print(f"  Version: {version}")
    print(f"\nNext steps:")
    print(f"  1. Run Inno Setup:  ISCC installer\\atana_setup.iss /DMyAppVersion={version}")
    print(f"     Output:          installer\\Output\\AtanaAgents_Setup_v{version}.exe")
    print(f"  2. Distribute the setup exe to clients")


def _sha256(path: Path) -> str:
    sha = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            sha.update(chunk)
    return sha.hexdigest()


if __name__ == "__main__":
    main()
